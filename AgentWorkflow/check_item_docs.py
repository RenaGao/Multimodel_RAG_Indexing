import os
import json
import argparse
from pathlib import Path
from typing import Any, Dict, List
import sys

# Import functions from buildRag.py
from buildRag import (
    normalize_item_docs_from_itemReview,
    load_json,
    get_files_for_category,
    DATA_DIR,
    BASE_DIR
)

def print_doc_sample(doc: Dict[str, Any], index: int):
    """Print a single document in a formatted way"""
    print(f"\n{'='*80}")
    print(f"Document #{index + 1}")
    print(f"{'='*80}")
    print(f"doc_id:   {doc.get('doc_id', 'N/A')}")
    print(f"item_id:  {doc.get('item_id', 'N/A')}")
    print(f"title:    {doc.get('title', 'N/A')[:100]}{'...' if len(doc.get('title', '')) > 100 else ''}")
    print(f"brand:    {doc.get('brand', 'N/A')}")
    print(f"price:    {doc.get('price', 'N/A')}")
    print(f"rating:   {doc.get('rating', 'N/A')}")
    print(f"source:   {doc.get('source', 'N/A')}")
    print(f"text:     {doc.get('text', 'N/A')[:200]}{'...' if len(doc.get('text', '')) > 200 else ''}")
    print(f"text_len: {len(doc.get('text', ''))}")

def print_statistics(docs: List[Dict[str, Any]]):
    """Print statistics about the documents"""
    print(f"\n{'='*80}")
    print("STATISTICS")
    print(f"{'='*80}")
    print(f"Total documents: {len(docs)}")

    if docs:
        # Count unique items
        unique_items = set(d.get('item_id') for d in docs)
        print(f"Unique items:    {len(unique_items)}")

        # Average text length
        avg_text_len = sum(len(d.get('text', '')) for d in docs) / len(docs)
        print(f"Avg text length: {avg_text_len:.2f} chars")

        # Rating distribution
        ratings = [d.get('rating') for d in docs if d.get('rating') is not None]
        if ratings:
            avg_rating = sum(ratings) / len(ratings)
            print(f"Avg rating:      {avg_rating:.2f}")
            print(f"Docs w/ rating:  {len(ratings)}/{len(docs)}")

        # Fields present
        print(f"\nFields in documents: {list(docs[0].keys())}")

def check_item_docs(category: str, num_samples: int = 5):
    """
    Check the documents generated by normalize_item_docs_from_itemReview

    Args:
        category: Category name (e.g., 'Amazon_Fashion', 'All_Beauty')
        num_samples: Number of sample documents to print to console
    """
    print(f"\n{'#'*80}")
    print(f"# Checking item documents for category: {category}")
    print(f"{'#'*80}\n")

    # Get file paths
    user_data_file, _ = get_files_for_category(category)
    print(f"Loading data from: {user_data_file}")

    # Check if file exists
    if not user_data_file.exists():
        print(f"ERROR: File not found: {user_data_file}")
        return

    # Load data
    all_users = load_json(user_data_file)
    if all_users is None:
        print(f"ERROR: Failed to load data from {user_data_file}")
        return

    print(f"Loaded data for {len(all_users) if isinstance(all_users, dict) else 'N/A'} users")

    # Generate documents
    print("\nGenerating documents...")
    docs = normalize_item_docs_from_itemReview(all_users)

    if not docs:
        print("WARNING: No documents generated!")
        return

    # Print statistics
    print_statistics(docs)

    # Print sample documents
    print(f"\n{'#'*80}")
    print(f"# Sample Documents (showing first {min(num_samples, len(docs))})")
    print(f"{'#'*80}")

    for i, doc in enumerate(docs[:num_samples]):
        print_doc_sample(doc, i)

    # Save to JSON file
    output_dir = BASE_DIR
    output_dir.mkdir(parents=True, exist_ok=True)
    output_file = output_dir / f"check_item_docs_{category}.json"

    print(f"\n{'='*80}")
    print(f"Saving all {len(docs)} documents to: {output_file}")
    print(f"{'='*80}")

    with output_file.open("w", encoding="utf-8") as f:
        json.dump(docs, f, ensure_ascii=False, indent=2)

    print(f"✓ Successfully saved to {output_file}")
    print(f"✓ File size: {output_file.stat().st_size / 1024:.2f} KB")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Check documents generated by normalize_item_docs_from_itemReview"
    )
    parser.add_argument(
        "--category",
        default="Amazon_Fashion",
        help="Category name (e.g., 'Amazon_Fashion', 'All_Beauty')"
    )
    parser.add_argument(
        "--samples",
        type=int,
        default=5,
        help="Number of sample documents to print (default: 5)"
    )

    args = parser.parse_args()

    check_item_docs(args.category, args.samples)
