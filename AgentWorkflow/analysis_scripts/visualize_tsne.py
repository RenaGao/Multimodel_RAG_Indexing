"""
t-SNE Visualization for Item Embeddings

This script loads the embeddings from matrix.pkl generated by buildRag.py
and creates t-SNE visualizations to explore the embedding space.

Usage:
    python visualize_tsne.py --category Amazon_Fashion
    python visualize_tsne.py --path ./storage/vectorstore/catalog/Amazon_Fashion/item_index
    python visualize_tsne.py --category Amazon_Fashion --perplexity 50 --max_iter 1500
"""

import os
import pickle
import argparse
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt
from sklearn.manifold import TSNE
from matplotlib import cm
import seaborn as sns

# Set style
sns.set_style("whitegrid")
plt.rcParams['figure.figsize'] = (12, 8)

BASE_DIR = Path("../storage")
CATALOG_DIR = BASE_DIR / "vectorstore" / "catalog"
OUTPUT_DIR = Path("./tsne_outputs")
OUTPUT_DIR.mkdir(exist_ok=True)


def load_embeddings_and_metadata(index_dir: Path):
    """
    Load embeddings from matrix.pkl and metadata from meta.pkl

    Args:
        index_dir: Path to the item_index directory

    Returns:
        tuple: (embeddings array, docs list, texts list)
    """
    matrix_path = index_dir / "matrix.pkl"
    meta_path = index_dir / "meta.pkl"

    if not matrix_path.exists():
        raise FileNotFoundError(f"Matrix file not found: {matrix_path}")

    print(f"Loading embeddings from {matrix_path}")
    with matrix_path.open("rb") as f:
        embeddings = pickle.load(f)

    docs = None
    texts = None
    if meta_path.exists():
        print(f"Loading metadata from {meta_path}")
        with meta_path.open("rb") as f:
            meta = pickle.load(f)
            docs = meta.get("docs", [])
            texts = meta.get("texts", [])

    print(f"Loaded {len(embeddings)} embeddings with dimension {embeddings.shape[1]}")

    return embeddings, docs, texts


def apply_tsne(embeddings, perplexity=30, max_iter=1000, random_state=42):
    """
    Apply t-SNE dimensionality reduction

    Args:
        embeddings: numpy array of embeddings
        perplexity: t-SNE perplexity parameter (5-50)
        max_iter: maximum number of iterations
        random_state: random seed for reproducibility

    Returns:
        numpy array of 2D coordinates
    """
    print(f"Applying t-SNE (perplexity={perplexity}, max_iter={max_iter})...")

    tsne = TSNE(
        n_components=2,
        perplexity=perplexity,
        max_iter=max_iter,
        random_state=random_state,
        verbose=1
    )

    coords_2d = tsne.fit_transform(embeddings)
    print("t-SNE completed!")

    return coords_2d


def plot_basic_tsne(coords_2d, output_path):
    """Create a basic t-SNE scatter plot"""
    plt.figure(figsize=(12, 8))
    plt.scatter(coords_2d[:, 0], coords_2d[:, 1], alpha=0.5, s=20)
    plt.title("t-SNE Visualization of Item Embeddings", fontsize=16)
    plt.xlabel("t-SNE Component 1", fontsize=12)
    plt.ylabel("t-SNE Component 2", fontsize=12)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved basic t-SNE plot to {output_path}")
    plt.close()


def plot_tsne_by_rating(coords_2d, docs, output_path):
    """Create t-SNE plot colored by rating"""
    if not docs:
        print("No metadata available, skipping rating plot")
        return

    ratings = []
    valid_coords = []

    for i, doc in enumerate(docs):
        rating = doc.get("rating")
        if rating is not None and i < len(coords_2d):
            ratings.append(float(rating))
            valid_coords.append(coords_2d[i])

    if not ratings:
        print("No rating data available, skipping rating plot")
        return

    ratings = np.array(ratings)
    valid_coords = np.array(valid_coords)

    plt.figure(figsize=(12, 8))
    scatter = plt.scatter(
        valid_coords[:, 0],
        valid_coords[:, 1],
        c=ratings,
        cmap='RdYlGn',
        alpha=0.6,
        s=20,
        vmin=1,
        vmax=5
    )
    plt.colorbar(scatter, label='Rating')
    plt.title("t-SNE Visualization Colored by Rating", fontsize=16)
    plt.xlabel("t-SNE Component 1", fontsize=12)
    plt.ylabel("t-SNE Component 2", fontsize=12)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved rating t-SNE plot to {output_path}")
    plt.close()


def plot_tsne_by_brand(coords_2d, docs, output_path, top_n=10):
    """Create t-SNE plot colored by brand (top N brands)"""
    if not docs:
        print("No metadata available, skipping brand plot")
        return

    brands = []
    for doc in docs:
        brand = doc.get("brand", "Unknown")
        brands.append(str(brand))

    # Get top N brands by frequency
    from collections import Counter
    brand_counts = Counter(brands)
    top_brands = [brand for brand, _ in brand_counts.most_common(top_n)]

    # Create color mapping
    brand_to_color = {}
    colors = []

    for i, brand in enumerate(brands):
        if brand in top_brands:
            if brand not in brand_to_color:
                brand_to_color[brand] = i % top_n
            colors.append(brand_to_color[brand])
        else:
            colors.append(-1)  # Other brands

    colors = np.array(colors)

    plt.figure(figsize=(14, 8))

    # Plot "Other" brands in gray
    other_mask = colors == -1
    if other_mask.any():
        plt.scatter(
            coords_2d[other_mask, 0],
            coords_2d[other_mask, 1],
            c='lightgray',
            alpha=0.3,
            s=10,
            label='Other brands'
        )

    # Plot top brands with distinct colors
    cmap = cm.get_cmap('tab10')
    for brand in top_brands:
        mask = np.array([b == brand for b in brands])
        if mask.any():
            color_idx = brand_to_color[brand]
            plt.scatter(
                coords_2d[mask, 0],
                coords_2d[mask, 1],
                c=[cmap(color_idx / 10)],
                alpha=0.6,
                s=20,
                label=brand[:30]  # Truncate long brand names
            )

    plt.title(f"t-SNE Visualization Colored by Brand (Top {top_n})", fontsize=16)
    plt.xlabel("t-SNE Component 1", fontsize=12)
    plt.ylabel("t-SNE Component 2", fontsize=12)
    plt.legend(bbox_to_anchor=(1.05, 1), loc='upper left', fontsize=8)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved brand t-SNE plot to {output_path}")
    plt.close()


def plot_tsne_density(coords_2d, output_path):
    """Create a density plot of the t-SNE embeddings"""
    plt.figure(figsize=(12, 8))

    # Create hexbin plot
    plt.hexbin(coords_2d[:, 0], coords_2d[:, 1], gridsize=50, cmap='YlOrRd', mincnt=1)
    plt.colorbar(label='Point Density')
    plt.title("t-SNE Visualization - Density Plot", fontsize=16)
    plt.xlabel("t-SNE Component 1", fontsize=12)
    plt.ylabel("t-SNE Component 2", fontsize=12)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved density t-SNE plot to {output_path}")
    plt.close()


def save_tsne_coordinates(coords_2d, docs, output_path):
    """Save t-SNE coordinates along with metadata to a file"""
    import json

    output_data = []
    for i, coord in enumerate(coords_2d):
        entry = {
            "tsne_x": float(coord[0]),
            "tsne_y": float(coord[1]),
        }

        if docs and i < len(docs):
            doc = docs[i]
            entry.update({
                "doc_id": doc.get("doc_id", ""),
                "item_id": doc.get("item_id", ""),
                "title": doc.get("title", ""),
                "brand": doc.get("brand", ""),
                "rating": doc.get("rating"),
            })

        output_data.append(entry)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)

    print(f"Saved t-SNE coordinates to {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Create t-SNE visualizations for item embeddings")
    parser.add_argument("--category", help="Category name (e.g., Amazon_Fashion)")
    parser.add_argument("--path", help="Direct path to item_index directory")
    parser.add_argument("--perplexity", type=int, default=30, help="t-SNE perplexity (default: 30)")
    parser.add_argument("--max_iter", type=int, default=1000, help="t-SNE max iterations (default: 1000)")
    parser.add_argument("--output_dir", help="Output directory for plots")

    args = parser.parse_args()

    # Determine index directory
    if args.path:
        index_dir = Path(args.path)
    elif args.category:
        index_dir = CATALOG_DIR / args.category / "item_index"
    else:
        print("Error: Please provide either --category or --path")
        return

    if not index_dir.exists():
        print(f"Error: Index directory not found: {index_dir}")
        return

    # Set output directory
    output_dir = Path(args.output_dir) if args.output_dir else OUTPUT_DIR
    output_dir.mkdir(exist_ok=True, parents=True)

    category_name = args.category or index_dir.parent.name

    print(f"\n{'='*60}")
    print(f"t-SNE Visualization for Category: {category_name}")
    print(f"{'='*60}\n")

    # Load data
    embeddings, docs, texts = load_embeddings_and_metadata(index_dir)

    # Apply t-SNE
    coords_2d = apply_tsne(embeddings, perplexity=args.perplexity, max_iter=args.max_iter)

    print(f"\nGenerating visualizations...")

    # Create various plots
    plot_basic_tsne(
        coords_2d,
        output_dir / f"{category_name}_tsne_basic.png"
    )

    plot_tsne_by_rating(
        coords_2d,
        docs,
        output_dir / f"{category_name}_tsne_by_rating.png"
    )

    plot_tsne_by_brand(
        coords_2d,
        docs,
        output_dir / f"{category_name}_tsne_by_brand.png",
        top_n=10
    )

    plot_tsne_density(
        coords_2d,
        output_dir / f"{category_name}_tsne_density.png"
    )

    # Save coordinates
    save_tsne_coordinates(
        coords_2d,
        docs,
        output_dir / f"{category_name}_tsne_coordinates.json"
    )

    print(f"\n{'='*60}")
    print(f"All visualizations saved to: {output_dir}")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()
